#include <iostream>
using namespace std;
//-----------------------------
int DIV(int, int);
float DIV(float, float);
//-----------------------------
int main(){
	cout << DIV(9, 4) << endl;
	cout << DIV(9.0f, 4.0f) << endl;
}
//-----------------------------
int DIV(int p, int q){
	return p / q;
}
//-----------------------------
float DIV(float p, float q){
	return p / q;
}

